def export_incident_dossier_markdown(db: Session, incident_id: UUID) -> str:
    """Generates a downloadable formal forensic incident report dossier in Markdown format."""
    incident = (
        db.query(Incident)
        .options(
            joinedload(Incident.lead_analyst),
            joinedload(Incident.alerts).joinedload(SecurityAlert.rule),
            joinedload(Incident.notes).joinedload(InvestigationNote.author),
        )
        .filter(Incident.id == incident_id)
        .first()
    )
    if not incident:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Incident with ID '{incident_id}' not found.",
        )

    lead_name = incident.lead_analyst.full_name if incident.lead_analyst else "Unassigned"
    created_str = incident.created_at.strftime("%Y-%m-%d %H:%M:%S UTC") if incident.created_at else "N/A"
    updated_str = incident.updated_at.strftime("%Y-%m-%d %H:%M:%S UTC") if incident.updated_at else "N/A"

    lines = [
        f"# Incident Investigation Dossier — {incident.incident_number}",
        "",
        "> **CONFIDENTIAL // SOC INCIDENT RESPONSE DOCUMENTATION**",
        "> Prepared in accordance with NIST SP 800-61 Rev 2 Incident Handling Guidelines.",
        "",
        "## 1. Case Metadata",
        f"- **Case Identifier**: `{incident.incident_number}`",
        f"- **Case UUID**: `{str(incident.id)}`",
        f"- **Incident Title**: {incident.title}",
        f"- **Severity Level**: `{incident.severity.value.upper()}`",
        f"- **Current Lifecycle Phase**: `{incident.status.value.upper()}`",
        f"- **Lead Incident Responder**: {lead_name}",
        f"- **Case Opened (UTC)**: {created_str}",
        f"- **Last Updated (UTC)**: {updated_str}",
        "",
        "## 2. Executive Incident Summary",
        incident.summary or "No executive narrative summary recorded.",
        "",
        "## 3. Containment & Remediation Actions",
        incident.containment_details or "No containment actions documented.",
        "",
        "## 4. Post-Mortem & Lessons Learned",
        incident.lessons_learned or "Post-incident review not yet completed.",
        "",
        "## 5. Correlated Security Alerts",
    ]

    if not incident.alerts:
        lines.append("*No security alerts linked to this case file.*")
    else:
        lines.append("| Alert ID | Severity | Status | Rule Code | Detection Rule Name | Source IP | Event Count |")
        lines.append("| :--- | :--- | :--- | :--- | :--- | :--- | :--- |")
        for alt in incident.alerts:
            rule_code = alt.rule.rule_code if alt.rule else "N/A"
            rule_name = alt.rule.name if alt.rule else alt.title
            lines.append(
                f"| `{str(alt.id)[:8]}...` | `{alt.severity.value}` | `{alt.status.value}` | `{rule_code}` | {rule_name} | `{alt.source_ip or 'N/A'}` | {alt.event_count} |"
            )

    lines.extend([
        "",
        "## 6. Chronological Investigation Notes & Forensic Journal",
    ])

    if not incident.notes:
        lines.append("*No investigation notes recorded for this case.*")
    else:
        for idx, note in enumerate(sorted(incident.notes, key=lambda n: n.created_at or datetime.min), start=1):
            author_name = note.author.full_name if note.author else "SOC System"
            note_time = note.created_at.strftime("%Y-%m-%d %H:%M:%S UTC") if note.created_at else "N/A"
            lines.extend([
                f"### Note #{idx} — [{note.note_type.value.upper()}] by {author_name} ({note_time})",
                note.content,
                "",
            ])

    lines.extend([
        "## 7. Chain of Custody & Non-Repudiation Verification",
        f"Report extracted on **{datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')}** from Sentinel SOC Platform.",
        "All state transitions, notes, and evidence references are recorded in the immutable `audit_events` ledger.",
        "",
        "---",
        "*End of Incident Dossier Report*",
    ])

    return "\n".join(lines)
