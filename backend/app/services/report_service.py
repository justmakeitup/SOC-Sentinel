def export_summary_csv(report: OperationalReportResponse) -> str:
    """Exports executive metrics and distribution counters as CSV."""
    headers = ["Metric Category", "Indicator Name", "Calculated Value", "Measurement Unit / Context"]
    rows = [
        ["Report Scope", "Start Date (UTC)", report.start_date, "ISO 8601 Timestamp"],
        ["Report Scope", "End Date (UTC)", report.end_date, "ISO 8601 Timestamp"],
        ["Volume", "Total Security Events", report.total_events, "Normalized Telemetry Records"],
        ["Volume", "Total Security Alerts", report.total_alerts, "Correlated Threat Findings"],
        ["Volume", "Total Incidents Declared", report.total_incidents, "Formal Investigation Dossiers"],
        [
            "MTTR",
            "Mean Time to Resolution (Minutes)",
            report.mttr_metrics.mean_time_to_resolve_minutes if report.mttr_metrics.mean_time_to_resolve_minutes is not None else "N/A",
            report.mttr_metrics.sample_description,
        ],
        [
            "MTTR",
            "Mean Time to Resolution (Hours)",
            report.mttr_metrics.mean_time_to_resolve_hours if report.mttr_metrics.mean_time_to_resolve_hours is not None else "N/A",
            report.mttr_metrics.sample_description,
        ],
    ]

    # Append Alert Severities
    for sev, cnt in report.alerts_by_severity.items():
        rows.append(["Alert Severity", f"Severity: {sev.upper()}", cnt, "Alert Findings Count"])

    # Append Incident Statuses
    for st, cnt in report.incidents_by_status.items():
        rows.append(["Incident Status", f"Status: {st.upper()}", cnt, "Incident Cases Count"])

    # Append Top Rules
    for r in report.alerts_by_rule:
        rows.append(["Detection Rules", f"{r.rule_code} - {r.rule_name}", r.count, f"Severity: {r.severity}"])

    return build_csv_response(headers, rows)


def export_events_csv(
    db: Session,
    start_date: Optional[str] = None,
    end_date: Optional[str] = None,
    event_category: Optional[str] = None,
    log_source_id: Optional[UUID] = None,
    limit: int = 2000,
) -> str:
    """Exports filtered raw security events as a sanitized CSV table."""
    start_dt, end_dt = parse_and_validate_date_range(start_date, end_date)
    query = db.query(NormalizedSecurityEvent).filter(
        NormalizedSecurityEvent.timestamp >= start_dt,
        NormalizedSecurityEvent.timestamp <= end_dt,
    )
    if event_category and event_category.lower() != "all":
        query = query.filter(NormalizedSecurityEvent.event_type == event_category)
    if log_source_id:
        query = query.filter(NormalizedSecurityEvent.log_source_id == log_source_id)

    events = query.order_by(NormalizedSecurityEvent.timestamp.desc()).limit(limit).all()

    headers = [
        "Event ID",
        "Timestamp (UTC)",
        "Event Type",
        "Action",
        "Severity",
        "Source IP",
        "Source Port",
        "Destination IP",
        "Destination Port",
        "User Name",
        "Host Name",
        "Log Source ID",
    ]
    rows = []
    for ev in events:
        rows.append([
            str(ev.id),
            ev.timestamp.isoformat() if ev.timestamp else "",
            ev.event_type,
            ev.event_action,
            ev.severity.value if hasattr(ev.severity, "value") else str(ev.severity),
            ev.source_ip or "",
            ev.source_port or "",
            ev.destination_ip or "",
            ev.destination_port or "",
            ev.user_name or "",
            ev.host_name or "",
            str(ev.log_source_id),
        ])

    return build_csv_response(headers, rows)


def export_alerts_csv(
    db: Session,
    start_date: Optional[str] = None,
    end_date: Optional[str] = None,
    limit: int = 2000,
) -> str:
    """Exports filtered alerts with detection rule attribution as a sanitized CSV table."""
    start_dt, end_dt = parse_and_validate_date_range(start_date, end_date)
    alerts = (
        db.query(SecurityAlert)
        .options(joinedload(SecurityAlert.rule))
        .filter(
            SecurityAlert.created_at >= start_dt,
            SecurityAlert.created_at <= end_dt,
        )
        .order_by(SecurityAlert.created_at.desc())
        .limit(limit)
        .all()
    )

    headers = [
        "Alert ID",
        "Created At (UTC)",
        "Rule Code",
        "Rule Name",
        "Severity",
        "Status",
        "Source IP",
        "Event Count",
        "Title",
        "Description",
        "Linked Incident ID",
    ]
    rows = []
    for a in alerts:
        rows.append([
            str(a.id),
            a.created_at.isoformat() if a.created_at else "",
            a.rule.rule_code if a.rule else "",
            a.rule.name if a.rule else "",
            a.severity.value if hasattr(a.severity, "value") else str(a.severity),
            a.status.value if hasattr(a.status, "value") else str(a.status),
            a.source_ip or "",
            a.event_count,
            a.title,
            a.description,
            str(a.incident_id) if a.incident_id else "",
        ])

    return build_csv_response(headers, rows)


def export_incidents_csv(
    db: Session,
    start_date: Optional[str] = None,
    end_date: Optional[str] = None,
) -> str:
    """Exports incident cases and MTTR indicators as a sanitized CSV table."""
    start_dt, end_dt = parse_and_validate_date_range(start_date, end_date)
    incidents = (
        db.query(Incident)
        .options(joinedload(Incident.lead_analyst), joinedload(Incident.alerts))
        .filter(
            Incident.created_at >= start_dt,
            Incident.created_at <= end_dt,
        )
        .order_by(Incident.created_at.desc())
        .all()
    )

    headers = [
        "Incident Number",
        "Created At (UTC)",
        "Updated At (UTC)",
        "Title",
        "Severity",
        "Status",
        "Lead Analyst",
        "Linked Alerts Count",
        "Containment Summary",
        "Post-Mortem Lessons",
    ]
    rows = []
    for inc in incidents:
        lead_name = inc.lead_analyst.full_name if inc.lead_analyst else "Unassigned"
        rows.append([
            inc.incident_number,
            inc.created_at.isoformat() if inc.created_at else "",
            inc.updated_at.isoformat() if inc.updated_at else "",
            inc.title,
            inc.severity.value if hasattr(inc.severity, "value") else str(inc.severity),
            inc.status.value if hasattr(inc.status, "value") else str(inc.status),
            lead_name,
            len(inc.alerts),
            inc.containment_details or "",
            inc.lessons_learned or "",
        ])

    return build_csv_response(headers, rows)


