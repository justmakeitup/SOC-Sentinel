def parse_and_validate_date_range(
    start_date_str: Optional[str] = None,
    end_date_str: Optional[str] = None,
) -> Tuple[datetime, datetime]:
    """Validates and parses UTC start and end bounds, ensuring start <= end."""
    now_utc = datetime.now(timezone.utc)

    # 1. Parse or default end_date
    if end_date_str:
        try:
            end_dt = datetime.fromisoformat(end_date_str.replace("Z", "+00:00"))
            if end_dt.tzinfo is None:
                end_dt = end_dt.replace(tzinfo=timezone.utc)
        except ValueError:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail=f"Invalid end_date format '{end_date_str}'. Expected ISO 8601 (e.g. YYYY-MM-DDTHH:MM:SSZ).",
            )
    else:
        end_dt = now_utc

    # 2. Parse or default start_date (default to 30 days prior to end_dt)
    if start_date_str:
        try:
            start_dt = datetime.fromisoformat(start_date_str.replace("Z", "+00:00"))
            if start_dt.tzinfo is None:
                start_dt = start_dt.replace(tzinfo=timezone.utc)
        except ValueError:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail=f"Invalid start_date format '{start_date_str}'. Expected ISO 8601 (e.g. YYYY-MM-DDTHH:MM:SSZ).",
            )
    else:
        start_dt = end_dt - timedelta(days=30)

    # 3. Enforce valid temporal ordering
    if start_dt > end_dt:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=(
                f"Invalid date range: start_date ({start_dt.isoformat()}) cannot be after "
                f"end_date ({end_dt.isoformat()})."
            ),
        )

    return start_dt, end_dt


def generate_operational_report(
    db: Session,
    start_date: Optional[str] = None,
    end_date: Optional[str] = None,
    event_category: Optional[str] = None,
    log_source_id: Optional[UUID] = None,
) -> OperationalReportResponse:
    """Calculates comprehensive operational security metrics from actual database telemetry."""
    start_dt, end_dt = parse_and_validate_date_range(start_date, end_date)

    # --------------------------------------------------------------------------
    # 1. Event Telemetry Aggregations
    # --------------------------------------------------------------------------
    events_query = db.query(NormalizedSecurityEvent).filter(
        NormalizedSecurityEvent.timestamp >= start_dt,
        NormalizedSecurityEvent.timestamp <= end_dt,
    )
    if event_category and event_category.lower() != "all":
        events_query = events_query.filter(NormalizedSecurityEvent.event_type == event_category)
    if log_source_id:
        events_query = events_query.filter(NormalizedSecurityEvent.log_source_id == log_source_id)

    total_events = events_query.count()

    # Time series daily volume
    date_group = func.date(NormalizedSecurityEvent.timestamp).label("day_str")
    ts_query = (
        db.query(date_group, func.count(NormalizedSecurityEvent.id).label("cnt"))
        .filter(
            NormalizedSecurityEvent.timestamp >= start_dt,
            NormalizedSecurityEvent.timestamp <= end_dt,
        )
    )
    if event_category and event_category.lower() != "all":
        ts_query = ts_query.filter(NormalizedSecurityEvent.event_type == event_category)
    if log_source_id:
        ts_query = ts_query.filter(NormalizedSecurityEvent.log_source_id == log_source_id)

    ts_results = ts_query.group_by("day_str").order_by("day_str").all()
    timeseries_points = [
        TimeSeriesPoint(timestamp=str(row[0]), count=row[1])
        for row in ts_results
        if row[0] is not None
    ]

    # Top Attacker Source IPs
    top_ips_query = (
        db.query(
            NormalizedSecurityEvent.source_ip,
            func.count(NormalizedSecurityEvent.id).label("cnt"),
        )
        .filter(
            NormalizedSecurityEvent.timestamp >= start_dt,
            NormalizedSecurityEvent.timestamp <= end_dt,
            NormalizedSecurityEvent.source_ip.isnot(None),
        )
        .group_by(NormalizedSecurityEvent.source_ip)
        .order_by(desc("cnt"))
        .limit(10)
        .all()
    )

    period_alerts = (
        db.query(SecurityAlert)
        .filter(
            SecurityAlert.created_at >= start_dt,
            SecurityAlert.created_at <= end_dt,
        )
        .all()
    )

    top_source_ips = []
    for row in top_ips_query:
        ip = row[0]
        ev_count = row[1]
        alt_count = sum(1 for a in period_alerts if a.source_ip == ip)
        top_source_ips.append(
            TopAttackerIP(ip=ip, event_count=ev_count, alert_count=alt_count)
        )

    # --------------------------------------------------------------------------
    # 2. Alert Analytics & Detection Rule Breakdown
    # --------------------------------------------------------------------------
    alerts_query = db.query(SecurityAlert).filter(
        SecurityAlert.created_at >= start_dt,
        SecurityAlert.created_at <= end_dt,
    )
    total_alerts = alerts_query.count()

    # Alerts by severity
    severity_results = (
        db.query(SecurityAlert.severity, func.count(SecurityAlert.id))
        .filter(
            SecurityAlert.created_at >= start_dt,
            SecurityAlert.created_at <= end_dt,
        )
        .group_by(SecurityAlert.severity)
        .all()
    )
    alerts_by_severity = {
        "critical": 0,
        "high": 0,
        "medium": 0,
        "low": 0,
        "informational": 0,
    }
    for sev, cnt in severity_results:
        key = sev.value if hasattr(sev, "value") else str(sev).lower()
        if key in alerts_by_severity:
            alerts_by_severity[key] = cnt
        else:
            alerts_by_severity[key] = cnt

    # Alerts by Detection Rule
    rule_counts_results = (
        db.query(
            DetectionRule.rule_code,
            DetectionRule.name,
            DetectionRule.severity,
            func.count(SecurityAlert.id).label("rule_alert_cnt"),
        )
        .join(SecurityAlert, SecurityAlert.rule_id == DetectionRule.id)
        .filter(
            SecurityAlert.created_at >= start_dt,
            SecurityAlert.created_at <= end_dt,
        )
        .group_by(DetectionRule.id, DetectionRule.rule_code, DetectionRule.name, DetectionRule.severity)
        .order_by(desc("rule_alert_cnt"))
        .all()
    )
    alerts_by_rule = [
        RuleAlertCount(
            rule_code=row[0],
            rule_name=row[1],
            severity=row[2].value if hasattr(row[2], "value") else str(row[2]),
            count=row[3],
        )
        for row in rule_counts_results
    ]

    # --------------------------------------------------------------------------
    # 3. Incident Lifecycle & Mean Time to Resolution (MTTR)
    # --------------------------------------------------------------------------
    incidents_query = db.query(Incident).filter(
        Incident.created_at >= start_dt,
        Incident.created_at <= end_dt,
    )
    total_incidents = incidents_query.count()

    incident_status_results = (
        db.query(Incident.status, func.count(Incident.id))
        .filter(
            Incident.created_at >= start_dt,
            Incident.created_at <= end_dt,
        )
        .group_by(Incident.status)
        .all()
    )
    incidents_by_status = {
        "open": 0,
        "investigating": 0,
        "containment": 0,
        "eradication": 0,
        "recovery": 0,
        "resolved": 0,
        "closed": 0,
    }
    for st, cnt in incident_status_results:
        key = st.value if hasattr(st, "value") else str(st).lower()
        incidents_by_status[key] = cnt

    # MTTR Calculation over resolved/closed cases
    resolved_cases = (
        db.query(Incident)
        .filter(
            Incident.created_at >= start_dt,
            Incident.created_at <= end_dt,
            Incident.status.in_([IncidentStatus.RESOLVED, IncidentStatus.CLOSED]),
        )
        .all()
    )

    resolved_count = len(resolved_cases)
    if resolved_count > 0:
        resolution_durations_mins = []
        for case in resolved_cases:
            if case.updated_at and case.created_at:
                diff_sec = (case.updated_at - case.created_at).total_seconds()
                resolution_durations_mins.append(max(0.0, diff_sec / 60.0))

        if resolution_durations_mins:
            avg_mins = sum(resolution_durations_mins) / len(resolution_durations_mins)
            avg_hours = avg_mins / 60.0
            mttr_metrics = MTTRMetric(
                mean_time_to_resolve_minutes=round(avg_mins, 2),
                mean_time_to_resolve_hours=round(avg_hours, 2),
                resolved_incidents_count=resolved_count,
                sample_description=f"Calculated across {resolved_count} resolved/closed case(s) within selected timeframe.",
            )
        else:
            mttr_metrics = MTTRMetric(
                mean_time_to_resolve_minutes=None,
                mean_time_to_resolve_hours=None,
                resolved_incidents_count=0,
                sample_description="Insufficient data: No resolution timestamps recorded.",
            )
    else:
        mttr_metrics = MTTRMetric(
            mean_time_to_resolve_minutes=None,
            mean_time_to_resolve_hours=None,
            resolved_incidents_count=0,
            sample_description="Insufficient data: 0 resolved or closed incidents in selected timeframe.",
        )

    # --------------------------------------------------------------------------
    # 4. Assemble Operational Report
    # --------------------------------------------------------------------------
    return OperationalReportResponse(
        start_date=start_dt.isoformat(),
        end_date=end_dt.isoformat(),
        event_category_filter=event_category,
        log_source_filter=str(log_source_id) if log_source_id else None,
        total_events=total_events,
        total_alerts=total_alerts,
        total_incidents=total_incidents,
        event_volume_timeseries=timeseries_points,
        alerts_by_severity=alerts_by_severity,
        alerts_by_rule=alerts_by_rule,
        incidents_by_status=incidents_by_status,
        mttr_metrics=mttr_metrics,
        top_source_ips=top_source_ips,
        metric_definitions=METRIC_DEFINITIONS,
        generated_at=datetime.now(timezone.utc),
    )


